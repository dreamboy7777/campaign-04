function campaignAsset(
  id: string,
  slot: string,
  label: string,
  description: string,
  assetId: string | undefined,
  prompt: string,
  status: 'empty' | 'ready' = 'ready',
) {
  return { id, slot, label, description, assetId, prompt, status, locked: status === 'ready' }
}

